// Only FR and EN exist: any other browser language reads English, which far
// more visitors understand than French (es/de/it users got French before).
let LANG = localStorage.getItem("sure-weather-lang")
  || (navigator.language || "en").slice(0, 2);
if (!I18N[LANG]) LANG = "en";

function tr(key, vars) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = tr(el.dataset.i18n);
    // Hints are line-clamped in CSS: the full text stays reachable on long-press.
    if (el.classList.contains("card__hint")) el.title = el.textContent;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = tr(el.dataset.i18nPh);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = tr(el.dataset.i18nTitle);
    // Icon-only buttons: screen readers ignore title, they need a name.
    el.setAttribute("aria-label", el.title);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", tr(el.dataset.i18nAria));
  });
  document.documentElement.lang = LANG;
}

function setLang(lang) {
  LANG = I18N[lang] ? lang : "en";
  localStorage.setItem("sure-weather-lang", LANG);
  applyI18n();
  // Full re-render (not just the timeline): hours/table/verdict/badges/
  // footer/sources all carry translated strings.
  if (typeof currentData !== "undefined" && currentData) {
    render(currentData, (typeof state !== "undefined" && state.hours) || 24);
  } else if (typeof lastMeteo !== "undefined" && lastMeteo) {
    renderTimeline(lastMeteo.times, lastMeteo.byTime);
  }
}

window.addEventListener("DOMContentLoaded", applyI18n);